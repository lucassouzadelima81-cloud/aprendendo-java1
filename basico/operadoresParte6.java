package flamingo.aprendendo.basico;

public class operadoresParte6 {
    // incremento e decremento

    static void main(String[] args) {
        int contador = 0;//1
        contador = contador + 1;//2
        contador += 1;//3
        contador++;

        contador = contador - 1;//2
        contador += 1;//1
        contador--;//0


        System.out.println(contador);
    }
}
